-- Цена в начислениях теперь только у группы (и индивидуальная у ученика):
-- цена курса осталась для витрины (решение владельца 2026-09-23). Группы
-- без своей цены раньше брали цену курса — переносим её в группу один раз,
-- чтобы суммы учеников этих групп не изменились. Только данные, схема та же:
-- колонка остаётся необязательной, обязательность держат форма и API.
UPDATE "Group" g
SET "price" = c."price"
FROM "Course" c
WHERE c.id = g."courseId"
  AND g."price" IS NULL
  AND c."price" IS NOT NULL;
