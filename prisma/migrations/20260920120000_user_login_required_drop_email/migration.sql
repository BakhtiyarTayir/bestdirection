-- Шаг 2 отказа от почты (PLAN-SALARY-PROFILE-BRANCH-2026-09-20.md, 4.1,
-- чек-лист 4.8). Шаг 1 уже в проде: логины выданы всем пользователям, пароли
-- розданы на руки, вход по логину проверен. Страховка «входит и логин, и
-- почта» больше не нужна.
--
-- Защитное заполнение ниже — не про сегодняшний прод (там пустых логинов
-- нет: UserLoginBackfillService закрыл их на шаге 1), а про то, что
-- `prisma migrate deploy` выполняется при старте контейнера api, и упавшая
-- миграция — это прод, который не поднимается, без отката. Поэтому перед
-- SET NOT NULL миграция сама себя подстраховывает, а не полагается на
-- состояние базы.
UPDATE "User" SET "login" = 'user' || substring("id" from 1 for 12) WHERE "login" IS NULL;

ALTER TABLE "User" ALTER COLUMN "login" SET NOT NULL;

-- Почта была опознавательным знаком до логина — теперь не нужна вовсе.
-- Удаление необратимо: адреса из этой колонки не вернуть (решение владельца).
DROP INDEX "User_email_key";
ALTER TABLE "User" DROP COLUMN "email";

-- Код на почту заменён кодом в Telegram (PasswordResetRequest, шаг 1) —
-- сама таблица кодов на почту больше не используется ни одним маршрутом.
DROP TABLE "EmailVerificationCode";
