/**
 * Счётчики в сайдбаре (домашки, заявки, должники) читаются по своим
 * эндпоинтам и опрашиваются раз в минуту. После мутации ждать минуту незачем:
 * действие дёргает это событие, и счётчики перечитываются сразу.
 *
 * Событие, а не общий стор: сайдбар и формы живут в разных ветках дерева, а
 * протаскивать колбэк через все страницы ради трёх чисел — дороже задачи.
 */
export const BADGE_REFRESH_EVENT = "badge-refresh";

export function refreshBadges() {
  if (typeof window === "undefined") return;
  window.dispatchEvent(new Event(BADGE_REFRESH_EVENT));
}
